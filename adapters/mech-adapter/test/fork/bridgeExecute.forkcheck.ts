import hre from 'hardhat';
import { strict as assert } from 'node:assert';
import { createPublicClient, createWalletClient, custom, formatEther } from 'viem';
import { BASE_MECH_POOL_WALLET_ADDRESS } from '../../src/config.js';

const CHAIN_ID = 100;
const NATIVE_XDAI = '0x0000000000000000000000000000000000000000';
const NATIVE_WETH_ON_BASE = '0x4200000000000000000000000000000000000006';

interface LifiQuote {
  tool: string;
  estimate: { toAmount: string; toAmountMin: string; executionDuration: number };
  transactionRequest: { to: `0x${string}`; data: `0x${string}`; value: string };
}

async function fetchQuote(amountWei: bigint): Promise<LifiQuote> {
  const url =
    `https://li.quest/v1/quote?fromChain=${CHAIN_ID}&toChain=8453` +
    `&fromToken=${NATIVE_XDAI}&toToken=${NATIVE_WETH_ON_BASE}` +
    `&fromAmount=${amountWei}&fromAddress=${BASE_MECH_POOL_WALLET_ADDRESS}`;
  const res = await fetch(url);
  const json = (await res.json()) as LifiQuote & { message?: string };
  if (!res.ok || json.message) throw new Error(`quote failed: ${json.message ?? res.status}`);
  return json;
}

describe('mech-adapter — bridge execution, real Hardhat fork proof (BION-DIRECTIVE-118/119)', function () {
  this.timeout(60_000);

  const client = createPublicClient({ transport: custom(hre.network.provider) });

  before(async () => {
    // Same real infra note as this arc's other Gnosis fork proofs — EDR refuses eth_call exactly
    // AT the pinned fork block for chains without baked-in hardfork-activation history.
    await hre.network.provider.request({ method: 'evm_mine', params: [] });
  });

  it('the real script\'s exact deposit call — a fresh, real, live LI.FI quote submitted as a real transaction — succeeds on the fork against BASE_MECH_POOL_WALLET\'s own real current balance', async () => {
    const balance = await client.getBalance({ address: BASE_MECH_POOL_WALLET_ADDRESS });
    assert.ok(balance > 0n, 'expected the real forked Tier B balance to be non-zero');

    const reserve = 500_000_000_000_000_000n; // 0.5 xDAI, same real default as the script itself
    assert.ok(balance > reserve, 'expected real balance to exceed the gas reserve on this fork');
    const bridgeAmount = balance - reserve;

    // Real, live call to the real LI.FI API — not stubbed. The real calldata this generates is
    // exactly what the real script would submit.
    const quote = await fetchQuote(bridgeAmount);
    console.log(`[fork] real live quote: tool=${quote.tool}, toAmount=${formatEther(BigInt(quote.estimate.toAmount))} ETH, duration=${quote.estimate.executionDuration}s`);
    assert.ok(BigInt(quote.estimate.toAmount) > 0n, 'expected a real, non-zero quoted output amount');

    await hre.network.provider.request({ method: 'hardhat_impersonateAccount', params: [BASE_MECH_POOL_WALLET_ADDRESS] });
    const walletClient = createWalletClient({ account: BASE_MECH_POOL_WALLET_ADDRESS, transport: custom(hre.network.provider) });

    const txHash = await walletClient.sendTransaction({
      to: quote.transactionRequest.to,
      data: quote.transactionRequest.data,
      value: BigInt(quote.transactionRequest.value),
      chain: null,
    });
    const receipt = await client.waitForTransactionReceipt({ hash: txHash });
    assert.equal(receipt.status, 'success', 'expected the real deposit transaction (real quote, real calldata) to succeed on the fork');
    console.log(`[fork] real deposit tx succeeded: ${txHash}`);
  });
});
